# Звук для «Last man on Earth», часть 1 (60 сек, без голоса). Запуск: python3 scripts/lastman1_sound.py
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from sfx import *  # noqa: F401,F403

# 1. Пустая улица (0–7)
add(bed(7.0, 200, 1500, 0.2, 0.5), 0.0, 0.25)                     # ветер в пустом городе
add(click(500, 0.3, 10) * 0.6, 0.15, 0.4)                          # дверь подъезда
for a in np.arange(0.75, 3.0, 0.33): add(thud(150, 0.08), a, 0.2)  # шаги
add(boom(1.8), 1.4, 0.9)                                           # хук: пустая улица
for a in np.arange(1.2, 7.0, 1.0): add(click(2500, 0.02, 400), a, 0.12, 0.6)   # реле светофора
add(chime(880, 6, 0.55), 1.6, 0.06, -0.5)                          # дверь машины открыта
add(whistle_echo(1400, 0.8, 4), 5.0, 0.35)                         # крик → эхо
add(flutter(0.9), 5.1, 0.35, 0.4)                                  # голуби взлетают
add(pad(5.0, [38, 45, 50]) * 0.7, 2.0, 0.25)

# 2. Первый час: звонок без ответа (7–14)
add(bed(7.0, 200, 1500, 0.3, 0.5), 7.0, 0.15)
add(ringback(2.0), 7.4, 0.25); add(ringback(2.0), 10.4, 0.3)
for i in range(3): add(ping(620, 0.15, 30), 11.75 + i * 0.18, 0.3)  # звонок сброшен
add(whoosh(0.3, 1500, 6000), 12.0, 0.25); add(whoosh(0.3, 1500, 6000), 12.9, 0.25)
for a in np.arange(13.0, 14.0, 0.1): add(click(3000, 0.01, 600), a, 0.05)

# 3. Свет ещё горит (14–21)
add(bed(7.0, 200, 1200, 0.5, 0.5), 14.0, 0.15)
add(crickets(4.5), 16.5, 0.08)
add(hum(7.0, 60) * 0.3, 14.0, 0.06)
for a in np.arange(19.5, 20.7, 0.1): add(click(4000, 0.02, 300), a, 0.08)   # мерцание
add(pad(6.0, [45, 52, 57]), 14.5, 0.2)

# 4. День 1: магазин (21–28)
add(hum(7.0, 120) * 0.4, 21.0, 0.08)
x = t(int(2.0 * SR)); add(norm(filt(rng.standard_normal(len(x)), 800, 4000)) * (0.4 + 0.6 * (np.sin(2 * np.pi * 9 * x) > 0)) * env(len(x), 0.1, 0.2), 21.0, 0.15)  # тележка
for a in (23.67, 24.53, 25.4): add(thud(160, 0.15), a, 0.4); add(click(1200, 0.06, 80), a, 0.2)
add(glug(1.3), 25.9, 0.35)
add(ping(1320, 0.8, 4), 27.3, 0.25)

# 5. День 2: город гаснет (28–35)
add(hum(3.6, 60) * 0.8, 28.0, 0.1)
for a in (29.0, 29.5, 30.0, 30.5, 31.0, 31.5): add(powerdown(1.2), a, 0.45, rng.uniform(-0.5, 0.5))
add(crickets(3.5), 31.5, 0.08)
add(shimmer(3.0, 500, 2000) * 0.6, 32.0, 0.3)
add(pad(4.0, [50, 57, 62, 66]), 31.5, 0.3)

# 6. День 3: вода (35–42)
add(water(2.0), 35.0, 0.3)
for i in range(10):
    a = 37.0 + i * 0.17
    if rng.random() > 0.35: add(water(0.1) * env(int(0.1 * SR), 0.01, 0.05), a, 0.35)
for a in np.arange(38.7, 40.0, 0.66): add(ping(1800, 0.2, 25), a, 0.3)   # капли
for a in (39.1, 39.35, 39.6): add(click(1500, 0.05, 120), a, 0.35)     # стучит по крану
add(glug(1.6), 40.4, 0.3)
add(pad(6.0, [48, 55, 60]) * 0.7, 35.5, 0.18)

# 7. Дни 4–5: пёс (42–49)
for a in rng.uniform(42.1, 48.5, 6): add(chirp(), a, 0.05, rng.uniform(-0.8, 0.8))
for a in np.arange(42.2, 44.6, 0.45): add(filt(bark(), None, 900), a, 0.35, 0.4)   # лай за дверью
add(click(400, 0.5, 6) * 0.5, 44.7, 0.4)                                   # дверь
for a in (45.0, 45.35, 46.1): add(bark(), a, 0.45, 0.2)
for a in np.arange(46.5, 48.6, 0.3): add(breath(0.18, 2500), a, 0.12)     # пёс дышит
add(pad(6.0, [55, 59, 62, 67]), 43.5, 0.25)

# 8. День 6: машина и пробка (49–55)
add(engine(3.4, 1.4), 49.0, 0.35)
add(bed(3.3, 300, 3000, 0.2, 0.3), 49.0, 0.15)
add(squeal(0.8), 52.3, 0.3)
add(engine(0.8, 0.7), 52.6, 0.2)
add(click(600, 0.15, 30), 54.0, 0.3)
add(bed(2.0, 200, 1200, 0.3, 0.5), 53.2, 0.15)
add(pad(2.5, [46, 53, 58]), 53.0, 0.25)

# 9. Ночь 7: свет вдали (55–60)
add(crickets(5.0), 55.0, 0.07)
add(click(3000, 0.03, 200), 56.67, 0.4)
add(pad(3.3, [38, 45, 49]) * 0.9, 56.7, 0.4)
for a in (57.0, 57.5): add(bark(), a, 0.4)
add(riser(1.6), 58.0, 0.4)
add(boom(1.0), 59.4, 0.9)

save("public/lastman1/sound.wav")
