# Звук пробы «капитан моря» (10 с): море, ветер, скрип, чайки, крики команды, лёгкая морская мелодия, удар в конце.
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from sfx import *  # noqa
F = 1 / 30
D = 10.0
# море: волны (медленные накаты шума) + ветер
n = int(D * SR); x = t(n)
waves = filt(noise(D), 120, 1800) * (0.55 + 0.45 * np.sin(2 * np.pi * 0.23 * x) ** 2)
add(norm(waves) * env(n, 0.6, 0.8), 0.0, 0.32)
add(norm(filt(noise(D), 600, 5000)) * (0.4 + 0.3 * np.sin(2 * np.pi * 0.11 * x)) * env(n, 1.0, 0.5), 0.0, 0.08, 0.3)
# скрип дерева и чайки
for a in (1.9, 4.6, 7.2): add(creak(0.6, 330), a, 0.12, -0.3)
for a in (0.6, 3.5, 4.1, 6.1): add(chirp(), a, 0.09, rng.uniform(-0.6, 0.6))
# весёлая морская мелодия (до 8.8 с), шаг 0.25 с
mel = [67, 72, 72, 74, 76, 74, 72, 69, 67, 72, 72, 74, 76, 79, 76, 74, 72, 74, 76, 77, 79, 77, 76, 74, 72, 72, 74, 76, 74, 72, 71, 72, 67, 67]
for i, m in enumerate(mel):
    a = 0.1 + i * 0.25
    if a > 8.75: break
    add(ping(440 * 2 ** ((m - 69) / 12), 0.35, 7), a, 0.13, 0.15)
for k, ch in enumerate([[48, 55, 64], [53, 57, 65], [55, 59, 67], [48, 55, 64]] * 2):
    a = 0.1 + k * 1.1
    if a < 8.7: add(pad(1.1, ch, 0.7), a, 0.1)
for a in np.arange(0.1, 8.7, 0.5): add(thud(90, 0.12), a, 0.12)
# колокол на корабле, крики команды
add(chime(880, 2, 0.35), 1.8, 0.16)
add(laugh(5, 360), 4.9, 0.3, -0.25); add(laugh(4, 450), 5.2, 0.26, 0.25); add(laugh(4, 400), 5.7, 0.2, 0.0)
add(whoosh(0.4, 500, 5000), 3.25, 0.15); add(whoosh(0.4, 500, 5000), 6.2, 0.15)
add(water(1.4, 1.2), 6.3, 0.18)
# дозорный ахнул, музыка обрывается, удар
add(breath(0.4, 2600), 7.95, 0.2)
add(boom(1.6), 8.86, 0.55)
add(riser(1.0), 7.8, 0.12)
add(pad(1.2, [49, 55, 58, 64], 0.9), 8.86, 0.25)
save("public/captain/sound.wav")
